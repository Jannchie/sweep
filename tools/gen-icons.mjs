// 从 @jannchie/icons 生成 sweep/src/icons_gen.rs：每个图标在每个像素尺寸下各一份像素对齐的 SVG。
// 用法：cd tools && npm install && npm run icons

import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { icons } from '@jannchie/icons/all'
import { toPaths } from '@jannchie/icons'

const require = createRequire(import.meta.url)
const { version } = require('@jannchie/icons/package.json')

// 界面里用到的图标：[Rust 枚举名, 图标名]
const USED = [
  ['Search', 'search'],
  ['X', 'x'],
  ['ChevronRight', 'chevron-right'],
  ['ChevronDown', 'chevron-down'],
  ['CornerLeftUp', 'corner-left-up'],
  ['Home', 'home'],
  ['Folder', 'folder'],
  ['FolderOpen', 'folder-open'],
  ['FolderSearch', 'folder-search-badge'],
  ['File', 'file'],
  ['Files', 'files'],
  ['HardDrive', 'hard-drive'],
  ['UsbDrive', 'usb-drive'],
  ['Cloud', 'cloud'],
  ['Trash', 'trash'],
  ['TrashX', 'trash-x'],
  ['Copy', 'copy'],
  ['ExternalLink', 'external-link'],
  ['Info', 'info'],
  ['Settings', 'settings'],
  ['Refresh', 'refresh'],
  ['Shield', 'shield'],
  ['AlertTriangle', 'alert-triangle'],
  ['AlertCircle', 'alert-circle'],
  ['CheckCircle', 'check-circle'],
  ['XCircle', 'x-circle'],
  ['Treemap', 'chart-treemap'],
  ['Broom', 'broom'],
  ['Stop', 'stop'],
  ['Play', 'play'],
  ['Target', 'target'],
  ['Package', 'package'],
  ['Globe', 'globe'],
  ['Clock', 'clock'],
]
const STYLE = { radius: 2, weight: 'regular' }
// 覆盖 12–40 设备像素：13–16pt 的图标在 100%–250% 缩放下都能取到对应尺寸。
const PX_MIN = 12
const PX_MAX = 40

const camel = name => name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())
const esc = v => String(v).replaceAll('&', '&amp;').replaceAll('"', '&quot;')
// 白色描边，运行时用 tint 着色。
const color = v => (v === 'currentColor' ? '#fff' : v)
const attrs = obj =>
  Object.entries(obj)
    // toPaths 对未设置的属性给出 undefined，原样写出会变成 stroke="undefined"，被渲染成黑色填充。
    .filter(([k, v]) => k !== 'aria-hidden' && v !== undefined && v !== null)
    .map(([k, v]) => ` ${k}="${esc(color(v))}"`)
    .join('')

function svg(icon, px) {
  const { svg: root, paths } = toPaths(icon, { ...STYLE, px })
  const body = paths.map(p => `<path${attrs(p)}/>`).join('')
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 24 24"${attrs(root)}>${body}</svg>`
}

const rows = USED.map(([variant, name]) => {
  const icon = icons[camel(name)] ?? icons[name]
  if (!icon) throw new Error(`unknown icon: ${name}`)
  const sizes = []
  for (let px = PX_MIN; px <= PX_MAX; px++) sizes.push(JSON.stringify(svg(icon, px)))
  return { variant, name, sizes }
})

const out = `// @generated by tools/gen-icons.mjs from @jannchie/icons ${version} (radius ${STYLE.radius}, ${STYLE.weight}). 不要手改。

pub const PX_MIN: u32 = ${PX_MIN};
pub const PX_MAX: u32 = ${PX_MAX};

// 列表里的图标不一定都已用到。
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Icon {
${rows.map(r => `    ${r.variant},`).join('\n')}
}

impl Icon {
    pub fn name(self) -> &'static str {
        match self {
${rows.map(r => `            Icon::${r.variant} => ${JSON.stringify(r.name)},`).join('\n')}
        }
    }

    /// 针对 \`px\` 设备像素做过像素对齐的 SVG（超出范围时取最近的尺寸）。
    pub fn svg(self, px: u32) -> &'static str {
        TABLE[self as usize][(px.clamp(PX_MIN, PX_MAX) - PX_MIN) as usize]
    }
}

static TABLE: [[&str; ${PX_MAX - PX_MIN + 1}]; ${rows.length}] = [
${rows.map(r => `    // ${r.name}\n    [\n${r.sizes.map(s => `        ${s},`).join('\n')}\n    ],`).join('\n')}
];
`
const target = new URL('../sweep/src/icons_gen.rs', import.meta.url)
writeFileSync(target, out)
console.log(`wrote ${rows.length} icons × ${PX_MAX - PX_MIN + 1} sizes`)
